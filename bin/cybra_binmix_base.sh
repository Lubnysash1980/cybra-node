#!/data/data/com.termux/files/usr/bin/bash
# CYBRA BINMIX BASE — генерує базовий модуль з guard + extension hook
# Usage: cybra_binmix_base.sh <n> <name> <cat>
set -u
N="${1:?n}"; NAME="${2:?name}"; CAT="${3:-custom}"
NN=$(printf '%03d' "$N")
CYBRA="$HOME/CYBRA"; cd "$CYBRA" || exit 1

# знайти або створити папку
DIR=""
for pat in "modules/module_${NN}_base" "modules/module_${N}_base" \
           "modules/module_${NN}_${NAME}" "modules/module_${N}_${NAME}"; do
  [ -d "$pat" ] && { DIR="$pat"; break; }
done
[ -z "$DIR" ] && { DIR="modules/module_${NN}_${NAME}"; mkdir -p "$DIR"; }

MAIN="$DIR/main.sh"
cat > "$MAIN" <<'MAIN_EOF'
#!/data/data/com.termux/files/usr/bin/bash
# module_NNN: NAME (CAT)
# generated by binmix-base
set -u

# ─── BINMIX GUARD ───
BINMIX_LIMIT=$((65*1024*1024))
SANDBOX="$HOME/CYBRA/sandbox"
mkdir -p "$SANDBOX"/{bin,tmp,keep,trash} 2>/dev/null
SIZE=$(du -sb "$SANDBOX" 2>/dev/null | awk '{print $1}' || echo 0)
if [ "${SIZE:-0}" -ge "$BINMIX_LIMIT" ]; then
  rm -rf "$SANDBOX/trash/"* "$SANDBOX/tmp/"* 2>/dev/null
  [ -x "$SANDBOX/sandbox_cleanup.sh" ] && "$SANDBOX/sandbox_cleanup.sh" >/dev/null 2>&1
fi
# ─── END GUARD ───

CYBRA="${CYBRA:-$HOME/CYBRA}"; cd "$CYBRA" 2>/dev/null || exit 1
LOG="$CYBRA/logs/module_NNN.log"; mkdir -p "$(dirname "$LOG")"
log() { echo "[$(date -u +%FT%TZ)] $*" >> "$LOG"; }
trap 'log "ERR line $LINENO"' ERR
ACTION="${1:-help}"; shift $(( $# > 0 ? 1 : 0 ))
KEY="cybra:CAT:data"
log "START NAME action=$ACTION"

# ─── EXTENSION HOOK (binmix-mixin додає сюди) ───
case "$ACTION" in
# <<<BINMIX_EXTENSIONS>>>

  help|*)
    echo "==== module_NNN: NAME ===="
    echo "  version: base"
    echo "  actions: help"
    echo "  hint: binmix-mixin докрутить add/list/delete поступово"
    ;;
esac
rc=$?; log "DONE rc=$rc"; exit $rc
MAIN_EOF

# підставити NNN/NAME/CAT
sed -i "s/NNN/${NN}/g; s/NAME/${NAME}/g; s/CAT/${CAT}/g" "$MAIN"
chmod +x "$MAIN"

# syntax check
if ! bash -n "$MAIN" 2>/dev/null; then
  echo "❌ syntax error: $MAIN"; exit 1
fi

# ctrl
mkdir -p controllers
CTRL="controllers/module_${NN}.ctrl.sh"
cat > "$CTRL" <<'CTRL_EOF'
#!/data/data/com.termux/files/usr/bin/bash
set -u
M="$1"; shift
[ -f "$M" ] || { echo "missing"; exit 2; }
[ $# -gt 0 ] && A=("$@") || A=("help")
bash "$M" "${A[@]}" </dev/null 2>&1
exit $?
CTRL_EOF
chmod +x "$CTRL"

echo "{\"status\":\"ok\",\"n\":$N,\"main\":\"$MAIN\",\"ctrl\":\"$CTRL\"}"
