#!/data/data/com.termux/files/usr/bin/bash
# program_writer_task_handler.sh
# Парламент викликає цей хендлер, передаючи задачу через $CYBRA_TASK_JSON.
# Генерує код програми через AI_BACKEND (ollama | groq | stub) і пише у programs/prog_<X>/main.py.

set -euo pipefail
cd "$HOME/CYBRA"

AI_BACKEND="${AI_BACKEND:-stub}"   # ollama | groq | stub
PROG=$(printf '%s' "${CYBRA_TASK_JSON:-{\}}" | python3 -c 'import sys,json;print(json.load(sys.stdin).get("prog","a"))')
PROMPT=$(printf '%s' "${CYBRA_TASK_JSON:-{\}}" | python3 -c 'import sys,json;print(json.load(sys.stdin).get("prompt",""))')

case "$PROG" in a|b) ;; *) echo '{"ok":false,"error":"bad prog"}'; exit 1;; esac

OUT_DIR="$HOME/CYBRA/programs/prog_${PROG}"
OUT_FILE="$OUT_DIR/main.py"
mkdir -p "$OUT_DIR"

gen_ollama() {
  local model="${OLLAMA_MODEL:-qwen2.5-coder:1.5b}"
  local host="${OLLAMA_HOST:-http://127.0.0.1:11434}"
  python3 - "$host" "$model" <<'PY' "$PROMPT"
import sys, json, urllib.request
host, model, prompt = sys.argv[1], sys.argv[2], sys.argv[3]
payload = {"model": model, "prompt": prompt, "stream": False,
           "options": {"temperature": 0.2}}
req = urllib.request.Request(host + "/api/generate",
    data=json.dumps(payload).encode(),
    headers={"Content-Type": "application/json"})
with urllib.request.urlopen(req, timeout=180) as r:
    data = json.load(r)
sys.stdout.write(data.get("response", ""))
PY
}

gen_groq() {
  : "${GROQ_API_KEY:?GROQ_API_KEY not set}"
  local model="${GROQ_MODEL:-llama-3.3-70b-versatile}"
  python3 - <<'PY' "$GROQ_API_KEY" "$model" "$PROMPT"
import sys, json, urllib.request
key, model, prompt = sys.argv[1], sys.argv[2], sys.argv[3]
payload = {"model": model, "temperature": 0.2,
           "messages": [
               {"role": "system", "content": "Ти асистент-програміст. Виводь ЛИШЕ код файлу. Без markdown."},
               {"role": "user", "content": prompt},
           ]}
req = urllib.request.Request("https://api.groq.com/openai/v1/chat/completions",
    data=json.dumps(payload).encode(),
    headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
with urllib.request.urlopen(req, timeout=180) as r:
    data = json.load(r)
sys.stdout.write(data["choices"][0]["message"]["content"])
PY
}

gen_stub() {
  cat <<'PY'
# TODO: AI backend не налаштований.
# Встановіть OLLAMA (локально) або GROQ_API_KEY і перезапустіть.
def main():
    print("stub program — налаштуйте AI_BACKEND")

if __name__ == "__main__":
    main()
PY
}

case "$AI_BACKEND" in
  ollama) CODE=$(gen_ollama) ;;
  groq)   CODE=$(gen_groq)   ;;
  stub|*) CODE=$(gen_stub)   ;;
esac

# прибрати markdown-обгортки, якщо AI їх додав
CODE=$(printf '%s' "$CODE" | python3 -c '
import sys, re
s = sys.stdin.read()
if s.startswith("```"):
    s = re.sub(r"^```[a-zA-Z]*\n?", "", s)
    s = re.sub(r"\n?```\s*$", "", s)
sys.stdout.write(s)
')

{
  echo "# generated by program_writer_task_handler.sh / backend=$AI_BACKEND"
  echo "# $(date -u +%FT%TZ)  prog=$PROG"
  printf '%s\n' "$CODE"
} > "$OUT_FILE"

BYTES=$(wc -c < "$OUT_FILE")
printf '{"ok":true,"prog":"%s","backend":"%s","path":"%s","bytes":%s}\n' \
  "$PROG" "$AI_BACKEND" "$OUT_FILE" "$BYTES"
